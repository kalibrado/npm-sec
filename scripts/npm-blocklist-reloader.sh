#!/bin/sh
set -eu

WATCH_DIR="${WATCH_DIR:-/watch}"
TARGET_DIR="${TARGET_DIR:-/target}"
CONTAINER_NAME="${CONTAINER_NAME:-npm}"

# Temps sans nouvel événement avant application
DEBOUNCE_SECONDS="${DEBOUNCE_SECONDS:-30}"

# Temps minimum entre deux restarts NPM
MIN_RESTART_INTERVAL="${MIN_RESTART_INTERVAL:-60}"

# Restart au premier démarrage du sidecar
RESTART_ON_INITIAL_SYNC="${RESTART_ON_INITIAL_SYNC:-false}"

LAST_APPLIED_HASH=""
LAST_RESTART_TS=0

log() {
  echo "[npm-reloader] $(date '+%Y-%m-%d %H:%M:%S') $*"
}

install_deps() {
  if ! command -v curl >/dev/null 2>&1 || ! command -v inotifywait >/dev/null 2>&1; then
    log "installing dependencies..."
    apk add --no-cache curl inotify-tools coreutils >/dev/null
  fi
}

ensure_dirs() {
  mkdir -p "${WATCH_DIR}" "${TARGET_DIR}"
}

ensure_safe_defaults() {
  if [ ! -s "${WATCH_DIR}/npm-blocklist.conf" ]; then
    log "creating safe default npm-blocklist.conf in watch dir"
    cat > "${WATCH_DIR}/npm-blocklist.conf" <<'EOF'
# Generated by NPM Security Dashboard
# Safe empty default

geo $npm_security_blocked_ip {
    default 0;
}

geo $npm_security_blocked_country {
    default 0;
}
EOF
  fi

  if [ ! -f "${WATCH_DIR}/blocklist.json" ]; then
    log "creating safe default blocklist.json in watch dir"
    cat > "${WATCH_DIR}/blocklist.json" <<'EOF'
{
  "blocked": [],
  "trusted": []
}
EOF
  fi
}

current_hash() {
  {
    if [ -f "${WATCH_DIR}/npm-blocklist.conf" ]; then
      echo "npm-blocklist.conf"
      sha256sum "${WATCH_DIR}/npm-blocklist.conf"
    fi

    if [ -f "${WATCH_DIR}/blocklist.json" ]; then
      echo "blocklist.json"
      sha256sum "${WATCH_DIR}/blocklist.json"
    fi
  } | sha256sum | awk '{print $1}'
}

sync_files() {
  ensure_safe_defaults

  if [ ! -s "${WATCH_DIR}/npm-blocklist.conf" ]; then
    log "ERROR: npm-blocklist.conf is empty, refusing to sync"
    return 1
  fi

  log "syncing files to ${TARGET_DIR}"

  cp "${WATCH_DIR}/npm-blocklist.conf" "${TARGET_DIR}/npm-blocklist.conf.tmp"
  mv "${TARGET_DIR}/npm-blocklist.conf.tmp" "${TARGET_DIR}/npm-blocklist.conf"

  if [ -f "${WATCH_DIR}/blocklist.json" ]; then
    cp "${WATCH_DIR}/blocklist.json" "${TARGET_DIR}/blocklist.json.tmp"
    mv "${TARGET_DIR}/blocklist.json.tmp" "${TARGET_DIR}/blocklist.json"
  fi
}

restart_npm() {
  now="$(date +%s)"
  elapsed=$((now - LAST_RESTART_TS))

  if [ "${LAST_RESTART_TS}" -ne 0 ] && [ "${elapsed}" -lt "${MIN_RESTART_INTERVAL}" ]; then
    wait_time=$((MIN_RESTART_INTERVAL - elapsed))
    log "cooldown active, waiting ${wait_time}s before restart"
    sleep "${wait_time}"

    # Re-sync juste avant le restart, au cas où une nouvelle modif est arrivée pendant le cooldown
    sync_files || return 1
  fi

  log "restarting container ${CONTAINER_NAME}"

  if curl --fail --silent --show-error \
    --unix-socket /var/run/docker.sock \
    -X POST "http://localhost/containers/${CONTAINER_NAME}/restart?t=3"; then
    LAST_RESTART_TS="$(date +%s)"
    log "restart requested successfully"
  else
    log "WARNING: restart failed"
    return 1
  fi
}

wait_for_quiet_period() {
  log "change detected, waiting for quiet period: ${DEBOUNCE_SECONDS}s"

  while inotifywait -q -r \
    -e close_write,create,delete,move \
    -t "${DEBOUNCE_SECONDS}" \
    "${WATCH_DIR}" >/dev/null 2>&1; do
    log "more changes detected, debounce timer reset"
  done

  log "quiet period reached"
}

apply_if_changed() {
  new_hash="$(current_hash)"

  if [ "${new_hash}" = "${LAST_APPLIED_HASH}" ]; then
    log "no content change, skipping sync/restart"
    return 0
  fi

  sync_files || return 1
  LAST_APPLIED_HASH="${new_hash}"
  restart_npm || true
}

main() {
  install_deps
  ensure_dirs
  ensure_safe_defaults

  log "watching: ${WATCH_DIR}"
  log "target: ${TARGET_DIR}"
  log "container: ${CONTAINER_NAME}"
  log "debounce: ${DEBOUNCE_SECONDS}s"
  log "min restart interval: ${MIN_RESTART_INTERVAL}s"

  initial_hash="$(current_hash)"
  sync_files || true
  LAST_APPLIED_HASH="${initial_hash}"

  if [ "${RESTART_ON_INITIAL_SYNC}" = "true" ]; then
    restart_npm || true
  fi

  while true; do
    inotifywait -q -r \
      -e close_write,create,delete,move \
      "${WATCH_DIR}" >/dev/null 2>&1 || true

    wait_for_quiet_period
    apply_if_changed
  done
}

main "$@"