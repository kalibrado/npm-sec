import json
import sqlite3
import ipaddress
import os
from datetime import datetime, timezone

from  config import APP_VERSION, EXPORT_DIR, INTERNAL_NETWORKS


def get_blocklist_items(conn: sqlite3.Connection) -> list[dict]:
    rows = conn.execute(
        "SELECT type, value, reason, created_at FROM blocklist ORDER BY type, value"
    ).fetchall()
    return [dict(r) for r in rows]


def get_trusted_items(conn: sqlite3.Connection) -> list[dict]:
    rows = conn.execute(
        "SELECT type, value, reason, created_at FROM trusted_entries ORDER BY type, value"
    ).fetchall()
    return [dict(r) for r in rows]


def render_blocklist_json(items: list[dict], trusted_items: list[dict] | None = None) -> dict:
    trusted_items = trusted_items or []
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "version": APP_VERSION,
        "count": len(items),
        "items": items,
        "trusted_count": len(trusted_items),
        "trusted_items": trusted_items,
    }


def _nginx_address(value: str) -> str:
    """Allow only normalized IP/CIDR tokens in generated Nginx configs."""
    value = (value or "").strip()
    if "/" in value:
        return str(ipaddress.ip_network(value, strict=False))
    return str(ipaddress.ip_address(value))


def render_nginx_blocklist(
    items: list[dict], trusted_items: list[dict] | None = None
) -> str:
    """HTTP-context snippet, intentionally inert until explicitly included by NPM."""
    blocked_addresses = []
    blocked_countries = []
    for item in items:
        kind, value = item.get("type"), item.get("value")
        if kind in {"ip", "cidr"}:
            blocked_addresses.append(_nginx_address(value))
        elif kind == "country":
            country = str(value or "").strip().upper()
            if len(country) != 2 or not country.isascii() or not country.isalpha():
                raise ValueError("Invalid ISO country code in blocklist")
            blocked_countries.append(country)

    trusted_addresses = [str(network) for network in INTERNAL_NETWORKS]
    for entry in trusted_items or []:
        if entry.get("type") in {"ip", "cidr"}:
            trusted_addresses.append(_nginx_address(entry.get("value")))

    lines = [
        "# Generated by NPM Security Dashboard. Include in NPM http_top.conf.",
        f"# version={APP_VERSION}",
        "geo $npm_security_blocked_ip {",
        "    default 0;",
        *[f"    {address} 1;" for address in sorted(set(blocked_addresses))],
        "}",
        "geo $npm_security_trusted_ip {",
        "    default 0;",
        *[f"    {address} 1;" for address in sorted(set(trusted_addresses))],
        "}",
    ]
    if blocked_countries:
        # GeoIP2 must be loaded and geoip2_data_country_code defined in NPM.
        lines.extend([
            "map $geoip2_data_country_code $npm_security_blocked_country {",
            "    default 0;",
            *[f"    {code} 1;" for code in sorted(set(blocked_countries))],
            "}",
        ])
    else:
        # No GeoIP2 dependency when country blocking is unused.
        lines.extend([
            "map $host $npm_security_blocked_country {",
            "    default 0;",
            "}",
        ])
    lines.extend([
        'map "$npm_security_trusted_ip:$npm_security_blocked_ip:$npm_security_blocked_country" $npm_security_deny {',
        "    default 0;",
        '    "0:1:0" 1;',
        '    "0:1:1" 1;',
        '    "0:0:1" 1;',
        "}",
        "",
    ])
    return "\n".join(lines)


def render_nginx_server_guard() -> str:
    """Server-context snippet included in NPM's server_proxy.conf."""
    return (
        "# Generated by NPM Security Dashboard. Include in server_proxy.conf.\n"
        "if ($npm_security_deny) { return 403; }\n"
    )


def _write_atomic(path, content: str):
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(content, encoding="utf-8")
    os.replace(tmp, path)


def write_blocklist_exports(items: list[dict], trusted_items: list[dict] | None = None) -> dict:
    EXPORT_DIR.mkdir(parents=True, exist_ok=True)
    json_path = EXPORT_DIR / "blocklist.json"
    nginx_path = EXPORT_DIR / "npm-blocklist.conf"

    json_payload = render_blocklist_json(items, trusted_items)
    server_guard_path = EXPORT_DIR / "npm-server-guard.conf"
    _write_atomic(json_path, json.dumps(json_payload, ensure_ascii=False, indent=2) + "\n")
    _write_atomic(nginx_path, render_nginx_blocklist(items, trusted_items))
    _write_atomic(server_guard_path, render_nginx_server_guard())

    return {
        "json_path": str(json_path),
        "nginx_path": str(nginx_path),
        "server_guard_path": str(server_guard_path),
        "count": len(items),
    }
