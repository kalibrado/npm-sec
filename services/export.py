import json
import sqlite3
from datetime import datetime, timezone

from  config import APP_VERSION, EXPORT_DIR


def get_blocklist_items(conn: sqlite3.Connection) -> list[dict]:
    rows = conn.execute(
        "SELECT type, value, reason, created_at FROM blocklist ORDER BY type, value"
    ).fetchall()
    return [dict(r) for r in rows]


def get_trusted_items(conn: sqlite3.Connection) -> list[dict]:
    rows = conn.execute(
        "SELECT type, value, reason, created_at FROM trusted_entries ORDER BY type, value"
    ).fetchall()
    return [dict(r) for r in rows]


def render_blocklist_json(items: list[dict], trusted_items: list[dict] | None = None) -> dict:
    trusted_items = trusted_items or []
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "version": APP_VERSION,
        "count": len(items),
        "items": items,
        "trusted_count": len(trusted_items),
        "trusted_items": trusted_items,
    }


def render_nginx_blocklist(items: list[dict]) -> str:
    ip_lines: list[str] = []
    cidr_lines: list[str] = []
    country_lines: list[str] = []

    for item in items:
        entry_type = item.get("type")
        value = item.get("value")
        if not value:
            continue
        if entry_type == "ip":
            ip_lines.append(f"    {value} 1;")
        elif entry_type == "cidr":
            cidr_lines.append(f"    {value} 1;")
        elif entry_type == "country":
            country_lines.append(f"    {value} 1;")

    return "\n".join([
        "# Generated by NPM Security Dashboard",
        f"# generated_at={datetime.now(timezone.utc).isoformat()}",
        f"# version={APP_VERSION}",
        "",
        "# IP + CIDR blocking. Include this file from nginx http/server context.",
        "geo $npm_security_blocked_ip {",
        "    default 0;",
        *(ip_lines or ["    # no IP block entries"]),
        *(cidr_lines or ["    # no CIDR block entries"]),
        "}",
        "",
        "# Country blocking. Requires $geoip2_data_country_code to exist in NPM/nginx.",
        "map $geoip2_data_country_code $npm_security_blocked_country {",
        "    default 0;",
        *(country_lines or ["    # no country block entries"]),
        "}",
        "",
        "# Usage example inside a server/location block:",
        "# if ($npm_security_blocked_ip) { return 444; }",
        "# if ($npm_security_blocked_country) { return 444; }",
        "",
    ])


def write_blocklist_exports(items: list[dict], trusted_items: list[dict] | None = None) -> dict:
    EXPORT_DIR.mkdir(parents=True, exist_ok=True)
    json_path = EXPORT_DIR / "blocklist.json"
    nginx_path = EXPORT_DIR / "npm-blocklist.conf"

    json_payload = render_blocklist_json(items, trusted_items)
    json_path.write_text(json.dumps(json_payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    nginx_path.write_text(render_nginx_blocklist(items), encoding="utf-8")

    return {
        "json_path": str(json_path),
        "nginx_path": str(nginx_path),
        "count": len(items),
    }
